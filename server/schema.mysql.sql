CREATE TABLE IF NOT EXISTS accounts (
  id VARCHAR(32) PRIMARY KEY,
  email VARCHAR(120) NOT NULL,
  password VARCHAR(80) NOT NULL,
  role VARCHAR(16) NOT NULL,
  name VARCHAR(80) NOT NULL,
  city VARCHAR(80) NOT NULL,
  entity_id VARCHAR(32) NOT NULL,
  headers VARCHAR(80) NOT NULL,
  credits INT NOT NULL,
  loaded INT NOT NULL,
  low_at INT NOT NULL,
  reseller_id VARCHAR(32) NULL,
  cli VARCHAR(32) NOT NULL
);

CREATE TABLE IF NOT EXISTS templates (
  id VARCHAR(16) PRIMARY KEY,
  account_id VARCHAR(32) NOT NULL,
  name VARCHAR(80) NOT NULL,
  channel VARCHAR(16) NOT NULL,
  header VARCHAR(16) NOT NULL,
  body VARCHAR(240) NOT NULL,
  dlt_id VARCHAR(32) NOT NULL
);

CREATE TABLE IF NOT EXISTS notices (
  id VARCHAR(16) PRIMARY KEY,
  account_id VARCHAR(32) NOT NULL,
  at VARCHAR(8) NOT NULL,
  channel VARCHAR(16) NOT NULL,
  header VARCHAR(16) NOT NULL,
  destination VARCHAR(16) NOT NULL,
  state VARCHAR(16) NOT NULL,
  clicks INT NOT NULL,
  note VARCHAR(240) NOT NULL
);

CREATE TABLE IF NOT EXISTS invoices (
  id VARCHAR(16) PRIMARY KEY,
  account_id VARCHAR(32) NOT NULL,
  on_date VARCHAR(32) NOT NULL,
  credits INT NOT NULL,
  source VARCHAR(80) NOT NULL
);

CREATE TABLE IF NOT EXISTS counters (
  name VARCHAR(32) PRIMARY KEY,
  value INT NOT NULL
);

CREATE TABLE IF NOT EXISTS sessions (
  token VARCHAR(80) PRIMARY KEY,
  account_id VARCHAR(32) NOT NULL
);

CREATE TABLE IF NOT EXISTS hooks (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  kind VARCHAR(32) NOT NULL,
  payload TEXT NOT NULL
);
